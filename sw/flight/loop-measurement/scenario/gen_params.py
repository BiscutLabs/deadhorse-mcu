#!/usr/bin/env python3
"""Generates src/params_gen.inc: biquad coefficients (designed for a 1 kHz loop)
and the sec()/tilt schedule tables. Instruction counts do not depend on values."""
import math, sys
fs = 1000.0
def notch(f0, Q):
    w = 2*math.pi*f0/fs; al = math.sin(w)/(2*Q); c = math.cos(w)
    a0 = 1+al
    return [1/a0, -2*c/a0, 1/a0, -2*c/a0, (1-al)/a0]          # b0 b1 b2 a1 a2
def lpf(f0, Q=1/math.sqrt(2)):
    w = 2*math.pi*f0/fs; al = math.sin(w)/(2*Q); c = math.cos(w)
    a0 = 1+al
    return [(1-c)/2/a0, (1-c)/a0, (1-c)/2/a0, -2*c/a0, (1-al)/a0]
n = notch(150, 4.0); l = lpf(90)
sec = [min(1.5, 1/max(math.cos(math.radians(90*i/16)), 1e-3)) for i in range(17)]
# tilt schedule vs transition variable: smoothstep-like, 0 = vertical, 1 = horizontal
tilt = [(3*(i/16)**2 - 2*(i/16)**3) for i in range(17)]
out = ["/* generated by scenario/gen_params.py - do not edit */"]
out.append(".notch = { %s }," % ", ".join(f"Q({v!r})" for v in n))
out.append(".lpf = { %s }," % ", ".join(f"Q({v!r})" for v in l))
out.append(".sec_lut = { %s }," % ", ".join(f"N({v!r})" for v in sec))
out.append(".tilt_lut = { %s }," % ", ".join(f"N({v!r})" for v in tilt))
open(sys.argv[1], "w").write("\n".join(out)+"\n")
